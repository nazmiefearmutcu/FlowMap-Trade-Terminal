"""Tests for app/scripts/requirements_pins.py: the win-arm64 rewrite and the hash guard.

Run from the repository root with:
    python3 -m unittest discover -s app/scripts/tests -p "test_*.py"
"""

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))

import requirements_pins as pins  # noqa: E402


def digest(letter: str) -> str:
    return letter * 64


def export(*entries: str) -> str:
    header = "# This file was autogenerated by uv\n#    uv export --locked\n"
    return header + "\n".join(entries) + "\n"


def hashed(requirement: str, *digests: str) -> str:
    lines = [f"{requirement} \\"]
    for index, value in enumerate(digests):
        tail = " \\" if index < len(digests) - 1 else ""
        lines.append(f"    --hash=sha256:{value}{tail}")
    lines.append("    # via flowmap-server")
    return "\n".join(lines)


def win_arm64_export() -> str:
    # Each excluded package has digests no other entry uses, so any leftover
    # hash line from a dropped entry is visible in the output.
    return export(
        hashed("ccxt==4.0.0", digest("a")),
        hashed("pyarrow==25.0.0", digest("c"), digest("d")),
        hashed("zlib-ng==1.0.0", digest("e")),
        hashed("aiohttp-fast-zlib==0.3.0", digest("f")),
        hashed("cryptography==49.0.0", digest("b")),
        hashed("numpy==2.0.0", digest("g")),
    )


def blocks(text: str) -> list[list[str]]:
    """Requirement blocks of an exported file: the head line and its hash lines."""
    found: list[list[str]] = []
    for line in text.splitlines():
        if line and not line[0].isspace() and not line.startswith("#"):
            found.append([line])
        elif line.strip().startswith("--hash=") and found:
            found[-1].append(line)
    return found


class RequirementsPinsTest(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.tmp_path = Path(directory.name)

    def write(self, text: str) -> Path:
        path = self.tmp_path / "reqs.txt"
        path.write_text(text, encoding="utf-8")
        return path

    def test_a_fully_hashed_export_passes(self):
        path = self.write(
            export(
                hashed("ccxt==4.0.0", digest("a")),
                hashed("numpy==2.0.0", digest("b"), digest("c")),
            )
        )
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            pins.check_hashes(path)
        self.assertIn("2 requirements, all hash-pinned", out.getvalue())

    def test_a_requirement_without_a_hash_fails_the_guard(self):
        bare = "ccxt==4.0.0\n    # via flowmap-server"
        path = self.write(export(hashed("numpy==2.0.0", digest("a")), bare))
        with self.assertRaises(SystemExit) as failure:
            pins.check_hashes(path)
        self.assertIn("ccxt==4.0.0", str(failure.exception))
        self.assertNotIn("numpy", str(failure.exception))

    def test_a_local_wheel_is_a_requirement_and_needs_its_hash(self):
        local = "./vendor/crocodile-0.3.2-py3-none-any.whl \\\n    # via flowmap-server"
        path = self.write(export(local))
        with self.assertRaises(SystemExit) as failure:
            pins.check_hashes(path)
        self.assertIn("crocodile", str(failure.exception))

    def test_an_empty_export_is_rejected(self):
        path = self.write(export())
        with self.assertRaises(SystemExit):
            pins.check_hashes(path)

    def test_win_arm64_drops_the_excluded_packages_and_their_hashes(self):
        path = self.write(win_arm64_export())
        pins.apply_win_arm64(path)
        text = path.read_text(encoding="utf-8")
        for name in ("pyarrow", "zlib-ng", "aiohttp-fast-zlib"):
            self.assertNotIn(name, text)
        for orphan in ("c", "d", "e", "f"):
            self.assertNotIn(
                digest(orphan), text, f"hash of a dropped entry left behind: {orphan}"
            )
        self.assertIn("ccxt==4.0.0", text)
        self.assertIn("numpy==2.0.0", text)

    def test_win_arm64_repins_cryptography_with_the_pinned_release_hashes(self):
        path = self.write(win_arm64_export())
        pins.apply_win_arm64(path)
        text = path.read_text(encoding="utf-8")
        self.assertIn("cryptography==46.0.3 \\", text)
        self.assertNotIn("cryptography==49.0.0", text)
        crypto = next(
            block for block in blocks(text) if block[0].startswith("cryptography==")
        )
        hashes = [
            line.strip().removeprefix("--hash=sha256:").rstrip(" \\")
            for line in crypto[1:]
        ]
        self.assertEqual(hashes, list(pins.REPIN["cryptography"][2]))
        self.assertNotIn(
            digest("b"), text, "the locked release's digest must not survive the re-pin"
        )

    def test_win_arm64_output_has_a_continuation_on_every_hash_but_the_last(self):
        path = self.write(win_arm64_export())
        pins.apply_win_arm64(path)
        for block in blocks(path.read_text(encoding="utf-8")):
            hash_lines = block[1:]
            for line in hash_lines[:-1]:
                self.assertTrue(line.rstrip().endswith("\\"), line)
            self.assertFalse(hash_lines[-1].rstrip().endswith("\\"), hash_lines[-1])
        pins.check_hashes(path)

    def test_win_arm64_refuses_an_unexpected_cryptography_version(self):
        text = win_arm64_export().replace("cryptography==49.0.0", "cryptography==48.0.1")
        path = self.write(text)
        with self.assertRaises(SystemExit) as failure:
            pins.apply_win_arm64(path)
        self.assertIn("expects cryptography==49.0.0", str(failure.exception))

    def test_win_arm64_fails_when_an_excluded_package_is_gone(self):
        text = win_arm64_export().replace("pyarrow==25.0.0", "pyarrow-stub==1.0.0")
        path = self.write(text)
        with self.assertRaises(SystemExit) as failure:
            pins.apply_win_arm64(path)
        self.assertIn("pyarrow", str(failure.exception))


if __name__ == "__main__":
    unittest.main()
